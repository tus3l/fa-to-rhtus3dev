BEGIN;

CREATE SCHEMA IF NOT EXISTS tus3dev;
REVOKE ALL ON SCHEMA tus3dev FROM PUBLIC;

CREATE TABLE IF NOT EXISTS tus3dev.users (
  id TEXT PRIMARY KEY,
  name TEXT NOT NULL,
  email TEXT NOT NULL UNIQUE,
  password_hash TEXT NOT NULL,
  salt TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS tus3dev.sessions (
  token_hash TEXT PRIMARY KEY,
  user_id TEXT NOT NULL REFERENCES tus3dev.users(id),
  csrf TEXT NOT NULL,
  expires_at TIMESTAMPTZ NOT NULL
);

CREATE TABLE IF NOT EXISTS tus3dev.clients (
  id TEXT PRIMARY KEY,
  user_id TEXT NOT NULL REFERENCES tus3dev.users(id),
  name TEXT NOT NULL,
  email TEXT,
  phone TEXT,
  data JSONB NOT NULL CHECK (jsonb_typeof(data) = 'object'),
  UNIQUE(id, user_id)
);

CREATE TABLE IF NOT EXISTS tus3dev.documents (
  id TEXT PRIMARY KEY,
  user_id TEXT NOT NULL REFERENCES tus3dev.users(id),
  client_id TEXT,
  number TEXT NOT NULL,
  revision INTEGER NOT NULL DEFAULT 1 CHECK (revision > 0),
  type TEXT NOT NULL CHECK (type IN ('invoice','payment-proof','receipt','handover','installments','financial','custom')),
  status TEXT NOT NULL DEFAULT 'Draft' CHECK (status IN ('Draft','Sent','Viewed','Awaiting Signature','Signed','Approved','Rejected','Cancelled','Expired')),
  content JSONB NOT NULL CHECK (jsonb_typeof(content) = 'object'),
  version INTEGER NOT NULL DEFAULT 1 CHECK (version > 0),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  approved_at TIMESTAMPTZ,
  archived BOOLEAN NOT NULL DEFAULT false,
  FOREIGN KEY(client_id, user_id) REFERENCES tus3dev.clients(id, user_id),
  UNIQUE(user_id, number, revision)
);

CREATE TABLE IF NOT EXISTS tus3dev.document_items (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  document_id TEXT NOT NULL REFERENCES tus3dev.documents(id) ON DELETE CASCADE,
  position INTEGER NOT NULL CHECK (position >= 0),
  data JSONB NOT NULL CHECK (jsonb_typeof(data) = 'object')
);

CREATE TABLE IF NOT EXISTS tus3dev.payments (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  document_id TEXT NOT NULL REFERENCES tus3dev.documents(id) ON DELETE CASCADE,
  position INTEGER NOT NULL CHECK (position >= 0),
  data JSONB NOT NULL CHECK (jsonb_typeof(data) = 'object')
);

CREATE TABLE IF NOT EXISTS tus3dev.bank_accounts (
  id TEXT PRIMARY KEY,
  user_id TEXT NOT NULL REFERENCES tus3dev.users(id),
  data JSONB NOT NULL CHECK (jsonb_typeof(data) = 'object')
);

CREATE TABLE IF NOT EXISTS tus3dev.settings (
  user_id TEXT PRIMARY KEY REFERENCES tus3dev.users(id),
  data JSONB NOT NULL CHECK (jsonb_typeof(data) = 'object')
);

CREATE TABLE IF NOT EXISTS tus3dev.signatures (
  id TEXT PRIMARY KEY,
  document_id TEXT NOT NULL UNIQUE REFERENCES tus3dev.documents(id),
  image TEXT NOT NULL,
  signer_name TEXT NOT NULL,
  signed_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  user_agent TEXT NOT NULL,
  content_hash TEXT NOT NULL CHECK (content_hash ~ '^[0-9a-f]{64}$')
);

CREATE TABLE IF NOT EXISTS tus3dev.document_links (
  id TEXT PRIMARY KEY,
  document_id TEXT NOT NULL REFERENCES tus3dev.documents(id),
  token_hash TEXT NOT NULL UNIQUE CHECK (token_hash ~ '^[0-9a-f]{64}$'),
  encrypted_token TEXT NOT NULL,
  expires_at TIMESTAMPTZ,
  revoked_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS tus3dev.document_events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  document_id TEXT NOT NULL REFERENCES tus3dev.documents(id),
  type TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  metadata JSONB NOT NULL DEFAULT '{}'::jsonb CHECK (jsonb_typeof(metadata) = 'object')
);

CREATE TABLE IF NOT EXISTS tus3dev.document_revisions (
  id TEXT PRIMARY KEY,
  document_id TEXT NOT NULL REFERENCES tus3dev.documents(id),
  revision INTEGER NOT NULL CHECK (revision > 0),
  content JSONB NOT NULL CHECK (jsonb_typeof(content) = 'object'),
  content_hash TEXT NOT NULL CHECK (content_hash ~ '^[0-9a-f]{64}$'),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE(document_id, revision)
);

CREATE INDEX IF NOT EXISTS documents_owner_status ON tus3dev.documents(user_id, status, updated_at);
CREATE INDEX IF NOT EXISTS clients_owner ON tus3dev.clients(user_id, name);
CREATE INDEX IF NOT EXISTS links_document ON tus3dev.document_links(document_id, revoked_at);
CREATE INDEX IF NOT EXISTS events_document ON tus3dev.document_events(document_id, created_at);
CREATE INDEX IF NOT EXISTS sessions_expiry ON tus3dev.sessions(expires_at);
CREATE INDEX IF NOT EXISTS items_document ON tus3dev.document_items(document_id, position);
CREATE INDEX IF NOT EXISTS payments_document ON tus3dev.payments(document_id, position);

CREATE OR REPLACE FUNCTION tus3dev.protect_approved_document()
RETURNS TRIGGER LANGUAGE plpgsql SET search_path = pg_catalog AS $$
BEGIN
  IF OLD.status = 'Approved' AND
    (to_jsonb(NEW) - 'archived' - 'updated_at') IS DISTINCT FROM
    (to_jsonb(OLD) - 'archived' - 'updated_at') THEN
    RAISE EXCEPTION 'Approved document content is immutable';
  END IF;
  RETURN NEW;
END;
$$;

CREATE OR REPLACE FUNCTION tus3dev.protect_audit_record()
RETURNS TRIGGER LANGUAGE plpgsql SET search_path = pg_catalog AS $$
BEGIN
  RAISE EXCEPTION 'Approved snapshot, signature, and audit records are immutable';
END;
$$;

CREATE OR REPLACE TRIGGER approved_document_immutable
  BEFORE UPDATE ON tus3dev.documents
  FOR EACH ROW EXECUTE FUNCTION tus3dev.protect_approved_document();

CREATE OR REPLACE TRIGGER signature_immutable
  BEFORE UPDATE OR DELETE ON tus3dev.signatures
  FOR EACH ROW EXECUTE FUNCTION tus3dev.protect_audit_record();

CREATE OR REPLACE TRIGGER revision_immutable
  BEFORE UPDATE OR DELETE ON tus3dev.document_revisions
  FOR EACH ROW EXECUTE FUNCTION tus3dev.protect_audit_record();

CREATE OR REPLACE TRIGGER event_immutable
  BEFORE UPDATE OR DELETE ON tus3dev.document_events
  FOR EACH ROW EXECUTE FUNCTION tus3dev.protect_audit_record();

ALTER TABLE tus3dev.users ENABLE ROW LEVEL SECURITY;
ALTER TABLE tus3dev.sessions ENABLE ROW LEVEL SECURITY;
ALTER TABLE tus3dev.clients ENABLE ROW LEVEL SECURITY;
ALTER TABLE tus3dev.documents ENABLE ROW LEVEL SECURITY;
ALTER TABLE tus3dev.document_items ENABLE ROW LEVEL SECURITY;
ALTER TABLE tus3dev.payments ENABLE ROW LEVEL SECURITY;
ALTER TABLE tus3dev.bank_accounts ENABLE ROW LEVEL SECURITY;
ALTER TABLE tus3dev.settings ENABLE ROW LEVEL SECURITY;
ALTER TABLE tus3dev.signatures ENABLE ROW LEVEL SECURITY;
ALTER TABLE tus3dev.document_links ENABLE ROW LEVEL SECURITY;
ALTER TABLE tus3dev.document_events ENABLE ROW LEVEL SECURITY;
ALTER TABLE tus3dev.document_revisions ENABLE ROW LEVEL SECURITY;

REVOKE ALL ON ALL TABLES IN SCHEMA tus3dev FROM PUBLIC;
REVOKE ALL ON ALL SEQUENCES IN SCHEMA tus3dev FROM PUBLIC;
REVOKE ALL ON ALL FUNCTIONS IN SCHEMA tus3dev FROM PUBLIC;

COMMIT;